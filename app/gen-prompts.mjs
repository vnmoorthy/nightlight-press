import { readFileSync, readdirSync, writeFileSync } from "node:fs";
const out = ["// generated by gen-prompts.mjs; do not edit"];
const pdir = new URL("../prompts/", import.meta.url);
for (const f of readdirSync(pdir).filter((x) => x.endsWith(".md")).sort()) out.push(`export const ${f.replace(/\.md$/, "").toUpperCase()} = ${JSON.stringify(readFileSync(new URL(f, pdir), "utf8"))};`);
const mdir = new URL("./migrations/", import.meta.url);
const migs = readdirSync(mdir).filter((x) => x.endsWith(".sql")).sort().map((f) => [f, readFileSync(new URL(f, mdir), "utf8")]);
out.push(`export const MIGRATIONS = ${JSON.stringify(migs)};`);
const fdir = new URL("./fonts/", import.meta.url);
const fonts = {}; for (const f of readdirSync(fdir).filter((x) => x.endsWith(".ttf"))) fonts[f.replace(/\.ttf$/, "")] = readFileSync(new URL(f, fdir)).toString("base64");
out.push(`export const FONTS = ${JSON.stringify(fonts)};`);
writeFileSync(new URL("./src/prompts.generated.js", import.meta.url), out.join("\n") + "\n");
console.log("prompts.generated.js written (" + migs.length + " migrations)");
